enum class BufferStatus { CountOnly, TooSmall, Invalid, Fill };
constexpr BufferStatus CheckBuffer(std::uint32_t count, const void* data) {
    return count == 0 ? BufferStatus::CountOnly :
        count < ModeCount ? BufferStatus::TooSmall :
        data == nullptr ? BufferStatus::Invalid : BufferStatus::Fill;
}
